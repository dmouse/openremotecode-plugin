import { readFile, writeFile } from "node:fs/promises"
const schema = JSON.parse(await readFile(new URL("../schema/activity-v1.schema.json", import.meta.url), "utf8"))
const kinds = schema.properties.kind.enum, states = schema.properties.state.enum
const header = "// Generated by scripts/generate-activity.mjs. Do not edit.\n"
const ts = header + `export const ACTIVITY_KINDS = ${JSON.stringify(kinds).replaceAll(',', ', ')} as const\n` +
  `export const ACTIVITY_STATES = ${JSON.stringify(states).replaceAll(',', ', ')} as const\n`
const dart = header + `const activityKinds = <String>[\n${kinds.map((s) => `  '${s}',`).join('\n')}\n];\n` +
  `const activityStates = <String>[\n${states.map((s) => `  '${s}',`).join('\n')}\n];\n`
for (const [path, text] of [["../src/protocol/activity.generated.ts", ts],
  ["../../../mobile/lib/features/chat/domain/activity.generated.dart", dart]]) {
  const url = new URL(path, import.meta.url)
  if (process.argv.includes("--check")) {
    if (await readFile(url, "utf8") !== text) throw new Error(`Stale activity identifiers: ${path}`)
  } else await writeFile(url, text)
}
